/** Dot-path lookup, e.g. t('admin.sidebar.hero') */
type TranslationNode = string | { [key: string]: TranslationNode };

function flattenForLookup(obj: TranslationNode, prefix = ''): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, value] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === 'string') {
      out[path] = value;
    } else {
      Object.assign(out, flattenForLookup(value, path));
    }
  }
  return out;
}

